// The public site's portfolio data — one array, easy to extend. Add a new
// project by adding an entry here; vimeoId for video, or images (paths
// under /public/images/work/...) for a photo-only project. See
// CONTENT_README.md at the project root for where to put the actual files.
export type WorkCategory = 'Architectural' | 'Commercial' | 'Events'

// Only meaningful on Architectural projects — lets the Property page split
// its showcase between still-building sites and finished properties.
export type PropertyType = 'Construction' | 'Property'

// CSS aspect-ratio value for the main video, e.g. '16/9', '9/16', '4/3'.
// Defaults to 16/9 when omitted — only needs setting for anything else
// (a vertical reel, a 4:3 edit).
export type AspectRatio = string

export type ExtraVideo = { label: string; vimeoId: string; aspect?: AspectRatio; thumb?: string }

export type WorkProject = {
  id: string
  title: string
  client: string
  category: WorkCategory
  type: string
  propertyType?: PropertyType
  vimeoId?: string
  aspect?: AspectRatio
  thumb?: string
  images?: string[]
  // Secondary clips for the same project — a "sold" or "coming soon"
  // sting, a vertical reel cut, etc. Shown in the detail view under the
  // main video, each sized to its own aspect ratio rather than forced
  // into 16:9.
  extraVideos?: ExtraVideo[]
  description?: string
}

